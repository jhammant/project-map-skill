#!/usr/bin/env bash
# Install /map and the project-map subagent into ~/.claude.
#   ./install.sh                     link the skill, write the agent, create the config
#   PROJECT_MAP_SKILLS="frontend-design:frontend-design,dataviz" ./install.sh
#                                    choose the design skills the agent preloads
# Re-run it after pulling: the agent file is generated from agent/project-map.md.
# Not a plugin on purpose: plugin subagents ignore hooks, and the write guard is a hook.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SKILLS="${CLAUDE_SKILLS_DIR:-$HOME/.claude/skills}"
AGENTS="${CLAUDE_AGENTS_DIR:-$HOME/.claude/agents}"
CONFIG="${PROJECT_MAP_CONFIG_DIR:-$HOME/.config/project-map}"
mkdir -p "$SKILLS" "$AGENTS"

if [ -e "$SKILLS/map" ] && [ ! -L "$SKILLS/map" ]; then
  echo "skip: $SKILLS/map exists and is not a symlink" >&2
else
  ln -sfn "$HERE/skill" "$SKILLS/map"
  echo "linked $SKILLS/map"
fi

# Design skills to preload: whatever is installed, unless PROJECT_MAP_SKILLS says otherwise.
if [ -n "${PROJECT_MAP_SKILLS+set}" ]; then
  preload="$PROJECT_MAP_SKILLS"
else
  preload=""
  if [ -n "$(find "$HOME/.claude/plugins" -path '*skills/frontend-design/SKILL.md' -print -quit 2>/dev/null)" ]; then
    preload="frontend-design:frontend-design"
  fi
  if [ -e "$SKILLS/impeccable" ]; then preload="${preload:+$preload,}impeccable"; fi
fi
python3 - "$HERE/agent/project-map.md" "$AGENTS/project-map.md" "$preload" <<'PY'
import sys
source, target, preload = sys.argv[1], sys.argv[2], sys.argv[3]
names = [n.strip() for n in preload.split(",") if n.strip()]
block = "skills:\n" + "".join(f"  - {n}\n" for n in names) if names else ""
text = open(source).read().replace("{{SKILLS}}", block, 1)
text = text.replace("---\n", "---\n# Generated by project-map-skill/install.sh from agent/project-map.md; edit that file.\n", 1)
open(target, "w").write(text)
PY
echo "wrote $AGENTS/project-map.md (preloads: ${preload:-none})"

if [ ! -e "$CONFIG/config.json" ]; then
  mkdir -p "$CONFIG" && chmod 700 "$CONFIG"
  cp "$HERE/config.example.json" "$CONFIG/config.json" && chmod 600 "$CONFIG/config.json"
  echo "created $CONFIG/config.json (maps stay local until you set publish.command)"
fi
echo "Done. Start a new Claude Code session and type /map."
